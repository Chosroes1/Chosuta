QString messageText(const QString &language,const Message &message,bool details){
    if(message.isEmpty())return {};
    QString text=translatedMessage(language,message.key);
    if(text.isEmpty())text=uiText(language,"Operation failed. See technical details.","操作未完成，请查看技术详情。","操作を完了できません。技術情報を確認してください。");
    auto arguments=message.arguments;
    if(message.key=="User rule: %1"&&!arguments.isEmpty()){
        const auto translated=translatedMessage(language,arguments[0]);if(!translated.isEmpty())arguments[0]=translated;
    }
    // Substitute simultaneously, so user text such as
    // "%2" cannot be consumed as another placeholder on a subsequent pass.
    text=formatMessage(text,arguments);
    if(details){auto raw=messageDetails(language,message);
        if(!raw.isEmpty())text+="\n"+uiText(language,"Technical details (original)","技术详情（原文）","技術情報（原文）")+":\n"+raw;
    }
    return text;
}
QString messageDetails(const QString &language,const Message &message){
    if(!message.key.isEmpty()&&translatedMessage(language,message.key).isEmpty())return message.text();
    return message.detail;
}
